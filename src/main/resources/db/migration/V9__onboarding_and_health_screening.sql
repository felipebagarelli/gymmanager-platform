-- V9: onboarding do aluno (C3) e triagem de saude (C4).
--   * student_training_profiles: objetivo, nivel, dias por semana, tempo por treino, onde treina e
--     equipamento (um por aluno; o aluno pode editar).
--   * health_screenings: cada resposta da triagem (historico; vale a mais recente). "answers" guarda
--     uma letra por pergunta (S/N). Qualquer "S" marca risco: a IA nao gera treino e o app recomenda
--     avaliacao medica/profissional.

CREATE TABLE student_training_profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL UNIQUE REFERENCES student_profiles(id),
    goal varchar(32) NOT NULL CHECK (goal IN ('HYPERTROPHY', 'WEIGHT_LOSS', 'STRENGTH', 'CONDITIONING', 'HEALTH')),
    level varchar(32) NOT NULL CHECK (level IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED')),
    days_per_week integer NOT NULL CHECK (days_per_week BETWEEN 1 AND 7),
    minutes_per_session integer NOT NULL CHECK (minutes_per_session BETWEEN 15 AND 180),
    location varchar(32) NOT NULL CHECK (location IN ('GYM', 'HOME', 'BODYWEIGHT')),
    equipment varchar(255),
    updated_at timestamp(6) without time zone NOT NULL
);

CREATE TABLE health_screenings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES student_profiles(id),
    version varchar(32) NOT NULL,
    answers varchar(32) NOT NULL,
    risk boolean NOT NULL,
    answered_at timestamp(6) without time zone NOT NULL
);
CREATE INDEX idx_health_screenings_student ON health_screenings (student_id, answered_at);

-- V8: cadastro aberto do aluno (Fase C1/C2).
--   * users.email_verified_at: e-mail confirmado. Quem ja existia conta como confirmado.
--   * student_profiles.guardian_*: responsavel legal de quem tem de 12 a 17 anos e quando ele autorizou.
--   * account_tokens: codigos de confirmacao de e-mail e de troca de senha, e o link do responsavel.
--     Guarda so o hash; o codigo/link vai por e-mail.
--   * legal_acceptances: registro de cada aceite (termos, privacidade, dados de saude, responsavel),
--     com a versao do documento, data, IP e aparelho.

ALTER TABLE users ADD COLUMN email_verified_at timestamp(6) without time zone;
UPDATE users SET email_verified_at = COALESCE(created_at, now());

ALTER TABLE student_profiles ADD COLUMN guardian_name varchar(120);
ALTER TABLE student_profiles ADD COLUMN guardian_email varchar(255);
ALTER TABLE student_profiles ADD COLUMN guardian_consent_at timestamp(6) without time zone;

CREATE TABLE account_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    purpose varchar(32) NOT NULL CHECK (purpose IN ('VERIFY_EMAIL', 'RESET_PASSWORD', 'GUARDIAN_CONSENT')),
    token_hash varchar(64) NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    expires_at timestamp(6) without time zone NOT NULL,
    used_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL
);
CREATE INDEX idx_account_tokens_user_purpose ON account_tokens (user_id, purpose);
CREATE INDEX idx_account_tokens_hash ON account_tokens (token_hash);

CREATE TABLE legal_acceptances (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    document varchar(32) NOT NULL CHECK (document IN ('TERMS', 'PRIVACY', 'HEALTH_DATA', 'GUARDIAN_CONSENT')),
    version varchar(64) NOT NULL,
    accepted_at timestamp(6) without time zone NOT NULL,
    ip varchar(64),
    user_agent varchar(255),
    guardian_name varchar(120),
    guardian_email varchar(255)
);
CREATE INDEX idx_legal_acceptances_user ON legal_acceptances (user_id);

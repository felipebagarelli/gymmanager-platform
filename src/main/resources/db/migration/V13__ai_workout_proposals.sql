-- V13: propostas de treino montadas pela IA (Fase D). Nada vira treino ate o aluno aceitar.
-- Cada proposta fica guardada (auditoria): o que foi pedido, o que a IA propos (ja validado pelo
-- servidor), quem aceitou/recusou e quando, os treinos criados e o custo em tokens.

CREATE TABLE ai_workout_proposals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES student_profiles(id),
    status varchar(16) NOT NULL CHECK (status IN ('PROPOSED', 'ACCEPTED', 'REJECTED', 'EXPIRED')),
    request_note varchar(300),
    proposal_json text NOT NULL,
    input_tokens bigint NOT NULL DEFAULT 0,
    output_tokens bigint NOT NULL DEFAULT 0,
    workout_ids varchar(255),
    created_at timestamp(6) without time zone NOT NULL,
    decided_at timestamp(6) without time zone
);
CREATE INDEX idx_ai_workout_proposals_student ON ai_workout_proposals (student_id, created_at);

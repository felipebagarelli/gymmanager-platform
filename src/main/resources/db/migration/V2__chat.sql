-- V2: chat entre personal e aluno (uma conversa por vinculo trainer_students).

CREATE TABLE conversations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainer_student_id bigint NOT NULL UNIQUE REFERENCES trainer_students (id),
    created_at timestamp(6),
    trainer_last_read_id bigint,
    student_last_read_id bigint
);

CREATE TABLE messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint NOT NULL REFERENCES conversations (id),
    sender_role varchar(255) NOT NULL CHECK (sender_role IN ('TRAINER', 'STUDENT')),
    body varchar(2000) NOT NULL,
    created_at timestamp(6) NOT NULL
);

CREATE INDEX idx_messages_conversation_id_id ON messages (conversation_id, id);

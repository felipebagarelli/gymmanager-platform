-- V4: cobranca. O aluno paga o personal (Stripe Connect); a plataforma retem uma porcentagem.

CREATE TABLE plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainer_id bigint NOT NULL REFERENCES trainer_profiles (id),
    name varchar(255) NOT NULL,
    description varchar(1000),
    price_cents integer NOT NULL CHECK (price_cents >= 100),
    active boolean NOT NULL,
    created_at timestamp(6) NOT NULL
);

CREATE INDEX idx_plans_trainer_id ON plans (trainer_id);

CREATE TABLE trainer_payout_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainer_id bigint NOT NULL UNIQUE REFERENCES trainer_profiles (id),
    stripe_account_id varchar(255) NOT NULL UNIQUE,
    charges_enabled boolean NOT NULL,
    updated_at timestamp(6) NOT NULL
);

CREATE TABLE subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES student_profiles (id),
    trainer_id bigint NOT NULL REFERENCES trainer_profiles (id),
    plan_id bigint NOT NULL REFERENCES plans (id),
    status varchar(255) NOT NULL CHECK (status IN ('PENDING', 'ACTIVE', 'PAST_DUE', 'CANCELED')),
    stripe_subscription_id varchar(255) UNIQUE,
    current_period_end timestamp(6),
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL
);

CREATE INDEX idx_subscriptions_student_id ON subscriptions (student_id);
CREATE INDEX idx_subscriptions_trainer_id ON subscriptions (trainer_id);

-- idempotencia dos webhooks: cada evento da Stripe e processado uma unica vez
CREATE TABLE billing_events (
    stripe_event_id varchar(255) PRIMARY KEY,
    received_at timestamp(6) NOT NULL
);

-- V10: plano da plataforma (GymManager Pro) para o aluno sem personal (C5).
-- Cobrado direto na conta da plataforma (sem Stripe Connect e sem repasse).
-- Quem confirma o pagamento e o webhook; o retorno do navegador nunca vale como prova.

CREATE TABLE platform_subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES student_profiles(id),
    status varchar(32) NOT NULL CHECK (status IN ('PENDING', 'TRIALING', 'ACTIVE', 'PAST_DUE', 'CANCELED')),
    billing_interval varchar(16) NOT NULL CHECK (billing_interval IN ('MONTHLY', 'YEARLY')),
    price_cents integer NOT NULL,
    stripe_subscription_id varchar(255) UNIQUE,
    current_period_end timestamp(6) without time zone,
    trial_end timestamp(6) without time zone,
    cancel_at_period_end boolean NOT NULL DEFAULT false,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL
);
CREATE INDEX idx_platform_subscriptions_student ON platform_subscriptions (student_id);
